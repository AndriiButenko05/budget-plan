-- ============================================================
--  Видима частина фото у карточці вішліста.
--  Запустити один раз у SQL Editor.
--
--  Карточка показує фото смужкою, тому високе фото обрізається
--  зверху й знизу — і видно середину замість того, що потрібно.
--  Тут зберігається точка, яка має лишатись у кадрі: «50% 30%».
--  Наявні записи отримують центр, тобто нічого не змінюється.
-- ============================================================

alter table public.wishlist_items
  add column if not exists image_position text not null default '50% 50%';

select title, image_path, image_position from public.wishlist_items;
